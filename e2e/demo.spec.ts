import { test, expect } from '@playwright/test';

test('登録・編集・年次/月次・削除・再読み込み', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByText('デモモード（入力内容は保存されません）')).toBeVisible();
  await page.getByRole('button', { name: '＋ 車両を登録' }).click();
  await page.getByLabel('登録番号').fill('見本 300 わ 0099');
  await page.getByLabel('車名・型式').fill('見本テスト車両');
  await page.getByLabel('排気量（cc）').fill('1500');
  await page.getByLabel('取得日', { exact: true }).fill('2024-04-01');
  await page.getByLabel('事業供用日').fill('2024-04-01');
  await page.getByLabel('取得価額（円・税抜）').fill('3000000');
  await page.getByRole('button', { name: '登録する', exact: true }).click();
  await expect(page.getByRole('heading', { name: '見本テスト車両' })).toBeVisible();
  const annual = page.getByRole('table', { name: '年次償却スケジュール' });
  await expect(annual.getByRole('cell', { name: '2,001,000円', exact: true })).toBeVisible();
  await page.getByLabel('月次の事業年度').selectOption('2027-03');
  await expect(page.getByRole('table', { name: '月次償却スケジュール' }).getByRole('cell', { name: '332,666円', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '編集する' }).click();
  await page.getByLabel('車名・型式').fill('見本編集後');
  await page.getByRole('button', { name: '変更を反映' }).click();
  await expect(page.getByRole('heading', { name: '見本編集後' })).toBeVisible();
  await page.getByRole('button', { name: '一覧に戻る' }).click();
  await page.getByPlaceholder('登録番号・車名').fill('0099');
  await expect(page.getByRole('table', { name: '車両一覧' }).getByRole('row')).toHaveCount(2);
  await page.getByRole('button', { name: '見本編集後', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '車両を削除', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('車両を削除しました');
  await page.reload();
  await expect(page.getByRole('table', { name: '車両一覧' }).getByRole('row')).toHaveCount(4);
  expect(await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage) }))).toEqual({ local: [], session: [] });
});

