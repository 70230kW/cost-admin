test('外部通信・エラーなし、メモに入力したHTMLを文字列で表示', async ({ page }) => {
  const errors: string[] = []; const external: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1') external.push(request.url()); });
  await page.goto('/');
  await page.getByRole('button', { name: '見本コンパクト', exact: true }).click();
  await page.getByRole('button', { name: '編集する' }).click();
  await page.getByLabel('メモ', { exact: true }).fill('<img src=x onerror=alert(1)>');
  await page.getByRole('button', { name: '変更を反映' }).click();
  await expect(page.getByText('<img src=x onerror=alert(1)>', { exact: true })).toBeVisible();
  expect(await page.locator('img').count()).toBe(0);
  expect(external).toEqual([]); expect(errors).toEqual([]);
});
